def load_limits(root: Path) -> dict:
    here = Path(__file__).resolve().parent
    for candidate in (here / "limits.json", root / "poseidon/checks/limits.json"):
        if candidate.is_file():
            return json.loads(candidate.read_text(encoding="utf-8"))
    raise SystemExit("FAIL [config] limits.json not found — failing closed")


def read(path: Path) -> str:
    # Normalise line endings: a multiline check must run against what the CI
    # runner will actually see, not against the local checkout's endings.
    return path.read_text(encoding="utf-8", errors="strict").replace("\r\n", "\n")


def section_body(text: str, title: str) -> tuple[str, int]:
    """Body of a `## <title>` section, and its offset. ('', -1) if absent."""
    m = re.search(rf"^##\s+{re.escape(title)}\s*$", text, re.MULTILINE)
    if not m:
        return "", -1
    rest = text[m.end():]
    nxt = re.search(r"^##\s+", rest, re.MULTILINE)
    return (rest[: nxt.start()] if nxt else rest), m.start()


def table_rows(text: str, section: str | None = None) -> list[list[str]]:
    """Data rows of markdown tables: header, separator, and skeleton rows dropped.

    A skeleton row is one where any cell is a bare `<placeholder>` — the shipped
    template rows. Validating those as real entries would make `<Medium>` a
    legal severity; `--strict-placeholders` is what flags them instead.
    """
    body = text if section is None else section_body(text, section)[0]
    rows: list[list[str]] = []
    for line in body.split("\n"):
        line = line.strip()
        if not line.startswith("|") or not line.endswith("|"):
            continue
        cells = [c.strip().replace(r"\|", "|")
                 for c in UNESCAPED_PIPE.split(line.strip("|"))]
        if all(set(c) <= set("- :") and c for c in cells):
            continue
        rows.append(cells)
    if not rows:
        return []
    return [r for r in rows[1:] if not any(SKELETON_CELL.match(c) for c in r)]


def unit_files(root: Path) -> list[Path]:
    d = root / "docs/features"
    if not d.is_dir():
        return []
    return sorted(p for p in d.glob("*.md") if p.name != "README.md")


def parse_unit(path: Path, text: str) -> dict:
    # Milestones are parsed from the `## Milestones` section only. The
    # Completion Report reuses `### J1` headings; counting those as milestones
    # is a real bug this scoping prevents.
    body, offset = section_body(text, "Milestones")
    if offset == -1:
        first = MILESTONE_ID.search(text)
        body = text[first.start():] if first else ""
        offset = first.start() if first else len(text)
    head = text[:offset]
    milestones = []
    marks = list(MILESTONE_ID.finditer(body))
    for i, m in enumerate(marks):
        end = marks[i + 1].start() if i + 1 < len(marks) else len(body)
        block = body[m.start():end]
        milestones.append({"id": m.group(1), "statuses": STATUS_LINE.findall(block)})
    dep_body, dep_off = section_body(text, "Dependencies")
    branch = re.search(r"^Branch:\s*`?([^`\n]+?)`?\s*$", head, re.MULTILINE)
    return {
        "id": path.stem,
        "status": (STATUS_LINE.findall(head) or [None])[0],
        "head_statuses": STATUS_LINE.findall(head),
        "milestones": milestones,
        "dependencies": set(UNIT_ID.findall(dep_body)) if dep_off != -1 else set(),
        "branch": branch.group(1) if branch else "",
    }


def milestone_status(ms: dict) -> str | None:
    return ms["statuses"][0] if len(ms["statuses"]) == 1 else None


def open_milestone(unit: dict) -> str:
    for ms in unit["milestones"]:
        if milestone_status(ms) != "Done":
            return ms["id"]
    return "—"


def walk_files(root: Path, limits: dict):
    ignored = set(limits["ignored_dirs"])
    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = Path(dirpath).relative_to(root).as_posix().lstrip("./")
        dirnames[:] = [
            d for d in dirnames
            if d not in ignored and f"{rel_dir}/{d}".lstrip("/") not in ignored
        ]
        for name in filenames:
            yield Path(dirpath) / name


