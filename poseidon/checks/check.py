def check_caps(root: Path, limits: dict, f: Failures) -> None:
    for rel, cap in limits["line_caps"].items():
        p = root / rel
        if not p.is_file():
            f.add("caps", rel, "declared in limits.json but missing — failing closed")
            continue
        n = len(read(p).rstrip("\n").split("\n"))
        if n > cap:
            f.add("caps", rel, f"{n} lines > cap {cap}. Condense; never raise the cap.")
    zone_cap = limits["zone_agents_cap"]
    # Walk, not glob: a vendored AGENTS.md under node_modules must not block CI
    # with an error the agent is forbidden from fixing.
    for p in walk_files(root, limits):
        if p.name != "AGENTS.md" or p.parent == root:
            continue
        n = len(read(p).rstrip("\n").split("\n"))
        if n > zone_cap:
            f.add("caps", p.relative_to(root), f"{n} lines > zone cap {zone_cap}")


def check_tracking(root: Path, limits: dict, f: Failures) -> None:
    units = unit_files(root)
    known = {p.stem for p in units}
    for p in units:
        rel = p.relative_to(root)
        u = parse_unit(p, read(p))

        if len(u["head_statuses"]) != 1:
            f.add("tracking", rel,
                  f"expected exactly one unit-level Status, found {len(u['head_statuses'])}")
        elif u["status"] not in limits["unit_states"]:
            f.add("tracking", rel, f"invalid unit Status {u['status']!r}")

        if not u["milestones"]:
            f.add("tracking", rel, "no milestone — a unit has at least one (J1)")
        for i, ms in enumerate(u["milestones"], start=1):
            if ms["id"] != f"J{i}":
                f.add("tracking", rel,
                      f"milestone sequence broken: expected J{i}, found {ms['id']}")
            if len(ms["statuses"]) != 1:
                f.add("tracking", rel,
                      f"{ms['id']}: expected exactly one Status, found {len(ms['statuses'])}")
            elif ms["statuses"][0] not in limits["milestone_states"]:
                f.add("tracking", rel,
                      f"{ms['id']}: invalid Status {ms['statuses'][0]!r}")

        # Milestones close in order: once one is not Done, none after it may be.
        seen_open = None
        for ms in u["milestones"]:
            if milestone_status(ms) != "Done":
                seen_open = seen_open or ms["id"]
            elif seen_open:
                f.add("tracking", rel,
                      f"{ms['id']} is Done while {seen_open} is not — "
                      "milestones close in order")

        all_done = bool(u["milestones"]) and all(
            milestone_status(ms) == "Done" for ms in u["milestones"])
        if u["status"] == "Ready" and all_done:
            f.add("tracking", rel, "Status: Ready but every milestone is Done")
        if u["status"] == "Done" and not all_done:
            f.add("tracking", rel,
                  "Status: Done but a milestone is not Done — a unit closes only "
                  "when every milestone has closed")
        if u["status"] in limits["unit_states_active"] and all_done:
            f.add("tracking", rel,
                  f"Status: {u['status']} but every milestone is Done — close the unit")

        for dep in u["dependencies"] - {u["id"]}:
            if dep not in known:
                f.add("tracking", rel, f"phantom dependency {dep} — no such unit file")


def check_current_state(root: Path, limits: dict, f: Failures) -> None:
    """The `Units in progress` table is hand-written and is what the router reads
    to find the active unit when the branch does not name it. Unchecked, it drifts."""
    p = root / "docs/CURRENT_STATE.md"
    if not p.is_file():
        f.add("current-state", "docs/CURRENT_STATE.md", "missing — failing closed")
        return
    rows = table_rows(read(p), "Units in progress")
    cap = limits["max_units_in_progress"]
    if len(rows) > cap:
        f.add("current-state", "docs/CURRENT_STATE.md",
              f"{len(rows)} units in progress > cap {cap}")
    known = {q.stem: parse_unit(q, read(q)) for q in unit_files(root)}
    for row in rows:
        if len(row) != 4:
            f.add("current-state", "docs/CURRENT_STATE.md",
                  f"row has {len(row)} columns, expected 4: {row}")
            continue
        uid = re.sub(r"[`\[\]()]", "", row[0]).split(".md")[0].strip()
        if uid not in known:
            f.add("current-state", "docs/CURRENT_STATE.md",
                  f"lists {uid}, which has no unit file")
            continue
        u = known[uid]
        if u["status"] not in limits["unit_states_active"]:
            f.add("current-state", "docs/CURRENT_STATE.md",
                  f"{uid} listed in progress but its Status is {u['status']!r}")
        listed = row[1].strip().split()[0] if row[1].strip() else ""
        actual = open_milestone(u)
        if listed and listed != actual:
            f.add("current-state", "docs/CURRENT_STATE.md",
                  f"{uid}: open milestone listed as {listed}, actually {actual}")


def render_index(root: Path) -> str:
    lines = ["# Units index", "", GENERATED_BANNER, "",
             "| Unit | Status | Open milestone | Branch |",
             "| --- | --- | --- | --- |"]
    for p in unit_files(root):
        u = parse_unit(p, read(p))
        lines.append(
            f"| [{u['id']}]({p.name}) | {u['status'] or '?'} "
            f"| {open_milestone(u)} | `{u['branch']}` |"
        )
    return "\n".join(lines) + "\n"


def check_index(root: Path, limits: dict, f: Failures, fix: bool = False) -> None:
    d = root / "docs/features"
    if not d.is_dir():
        if fix:
            return
        f.add("index", "docs/features/", "missing — the units directory is required")
        return
    target = d / "README.md"
    expected = render_index(root)
    if fix:
        target.write_text(expected, encoding="utf-8")
        return
    if not target.is_file():
        f.add("index", "docs/features/README.md", "missing — run --fix-index")
        return
    if read(target) != expected:
        f.add("index", "docs/features/README.md",
              "out of date. Run --fix-index; never hand-edit a generated index.")


def check_headings(root: Path, limits: dict, f: Failures) -> None:
    for rel in limits["no_unit_id_in_headings"]:
        p = root / rel
        if not p.is_file():
            f.add("headings", rel, "missing — failing closed")
            continue
        for line_no, line in enumerate(read(p).split("\n"), start=1):
            if line.startswith("#") and ANY_ID.search(line):
                f.add("headings", f"{rel}:{line_no}",
                      "identifier in a heading. Move it to the "
                      "'Proven by' / 'Promoted from' column and drop the narrative.")


def check_registries(root: Path, limits: dict, f: Failures) -> None:
    ki = root / "docs/KNOWN_ISSUES.md"
    if not ki.is_file():
        f.add("registries", "docs/KNOWN_ISSUES.md", "missing — failing closed")
    else:
        seen: set[str] = set()
        for row in table_rows(read(ki), "Entries"):
            if len(row) != 7:
                f.add("registries", "docs/KNOWN_ISSUES.md",
                      f"row has {len(row)} columns, expected 7: {row}")
                continue
            rid, sev, _area, _summary, evidence, _target, status = row
            if rid in seen:
                f.add("registries", "docs/KNOWN_ISSUES.md", f"duplicate id {rid}")
            seen.add(rid)
            if sev not in limits["issue_severities"]:
                f.add("registries", "docs/KNOWN_ISSUES.md", f"{rid}: invalid severity {sev!r}")
            if status not in limits["issue_statuses"]:
                f.add("registries", "docs/KNOWN_ISSUES.md", f"{rid}: invalid status {status!r}")
            if status == "Resolved" and not evidence.strip():
                f.add("registries", "docs/KNOWN_ISSUES.md",
                      f"{rid}: Resolved with empty evidence — a false success, not a success")

    lr = root / "docs/LEARNINGS.md"
    if not lr.is_file():
        f.add("registries", "docs/LEARNINGS.md", "missing — failing closed")
    else:
        seen = set()
        for row in table_rows(read(lr), "Register"):
            if len(row) != 5:
                f.add("registries", "docs/LEARNINGS.md",
                      f"row has {len(row)} columns, expected 5: {row}")
                continue
            lid, _title, state, _dest, revalidate = row
            if lid in seen:
                f.add("registries", "docs/LEARNINGS.md", f"duplicate id {lid}")
            seen.add(lid)
            if state not in limits["learning_states"]:
                f.add("registries", "docs/LEARNINGS.md", f"{lid}: invalid state {state!r}")
            if state in limits["learning_states_needing_revalidation"] \
                    and not revalidate.strip():
                f.add("registries", "docs/LEARNINGS.md",
                      f"{lid}: promoted state with no revalidation date")


def registry_ids(root: Path) -> set[str]:
    ids: set[str] = set()
    for rel in ("docs/KNOWN_ISSUES.md", "docs/LEARNINGS.md"):
        p = root / rel
        if p.is_file():
            ids |= set(REF_ID.findall(read(p)))
    return ids


def scan_markers(root: Path, limits: dict) -> tuple[dict[str, list[int]], list[tuple[str, int, str]], list[str]]:
    """Returns (unregistered markers by file, bad references, unreadable files).

    `poseidon/` is excluded by ignored_dirs: the method is not the project, and
    its own fixture strings contain marker words."""
    known = registry_ids(root)
    exts = set(limits["code_extensions"])
    words = "|".join(limits["marker_words"])
    marker = re.compile(rf"(?<![A-Za-z0-9_])({words})(?![A-Za-z0-9_])")
    unregistered: dict[str, list[int]] = {}
    bad: list[tuple[str, int, str]] = []
    unreadable: list[str] = []
    for p in walk_files(root, limits):
        if p.suffix not in exts:
            continue
        rel = p.relative_to(root).as_posix()
        try:
            text = read(p)
        except (UnicodeDecodeError, OSError):
            unreadable.append(rel)
            continue
        for line_no, line in enumerate(text.split("\n"), start=1):
            if not marker.search(line):
                continue
            ids = REF_ID.findall(line)
            if not ids:
                unregistered.setdefault(rel, []).append(line_no)
            for i in ids:
                if i not in known:  # exact id, not substring
                    bad.append((rel, line_no, i))
    return unregistered, bad, unreadable


def load_adoption(root: Path, limits: dict) -> dict[str, int]:
    """Markers grandfathered when the kit was adopted into an existing repo.

    Without this, day one on a real codebase is hundreds of failures, CI goes
    red, and the checks get switched off — which costs more than the debt did.
    The ratchet freezes existing debt and blocks new debt; it never permits more.
    """
    p = root / limits["adoption_file"]
    if not p.is_file():
        return {}
    try:
        return dict(json.loads(read(p)).get("markers", {}))
    except (json.JSONDecodeError, TypeError, ValueError):
        return {}  # malformed → grandfather nothing, i.e. fail closed


def check_markers(root: Path, limits: dict, f: Failures) -> None:
    unregistered, bad, unreadable = scan_markers(root, limits)
    grandfathered = load_adoption(root, limits)
    for rel in unreadable:
        f.add("markers", rel, "unreadable — failing closed")
    for rel, lines in sorted(unregistered.items()):
        allowed = grandfathered.get(rel, 0)
        if len(lines) <= allowed:
            continue
        shown = ", ".join(str(n) for n in lines[:5]) + ("…" if len(lines) > 5 else "")
        if allowed:
            f.add("markers", rel,
                  f"{len(lines)} unregistered markers, {len(lines) - allowed} more than "
                  f"the {allowed} grandfathered at adoption (lines {shown}). Register the "
                  "new ones in KNOWN_ISSUES.md or remove them.")
        else:
            for n in lines:
                f.add("markers", f"{rel}:{n}",
                      "marker with no registry entry. Open a KNOWN_ISSUES.md entry "
                      "or delete the marker.")
    for rel, n, i in bad:  # a wrong reference is never grandfathered
        f.add("markers", f"{rel}:{n}", f"marker cites unknown entry {i}")


def check_baselines(root: Path, limits: dict, f: Failures) -> None:
    """Guardrail counters live in data, not prose, so a run that discovers less
    than its baseline fails on its own instead of depending on a paragraph."""
    rel = limits["baselines_file"]
    p = root / rel
    if not p.is_file():
        f.add("baselines", rel,
              "missing — create it (install.sh does) or drop the reference "
              "from docs/VALIDATION.md")
        return
    try:
        data = json.loads(read(p))
    except json.JSONDecodeError as exc:
        f.add("baselines", rel, f"invalid JSON ({exc}) — failing closed")
        return
    if not isinstance(data, dict):
        f.add("baselines", rel, "top level must be an object of suite -> entry")
        return
    for name, entry in data.items():
        if name.startswith("_"):
            continue
        if not isinstance(entry, dict):
            f.add("baselines", rel, f"{name}: entry must be an object")
            continue
        n = entry.get("discovered")
        if not isinstance(n, int) or isinstance(n, bool) or n < 0:
            f.add("baselines", rel, f"{name}: 'discovered' must be an integer >= 0")
        if not UNIT_ID.fullmatch(str(entry.get("raised_by", ""))):
            f.add("baselines", rel,
                  f"{name}: 'raised_by' must name the unit that added the tests "
                  "(a baseline rises only there)")


def check_boundaries(root: Path, limits: dict, f: Failures) -> None:
    """Every boundary declared in ARCHITECTURE.md is a section of RULES.md.

    This is the correspondence that makes documentation indexed by boundary
    rather than by history: if the two drift, RULES.md silently stops covering
    part of the system.
    """
    arch = root / "docs/ARCHITECTURE.md"
    rules = root / "docs/RULES.md"
    for p in (arch, rules):
        if not p.is_file():
            f.add("boundaries", p.relative_to(root), "missing — failing closed")
            return
    declared = [row[0] for row in table_rows(read(arch), "Boundaries") if row]
    sections = {m.strip().lower() for m in
                re.findall(r"^##\s+(.+?)\s*$", read(rules), re.MULTILINE)}
    for name in declared:
        clean = re.sub(r"[`*]", "", name).strip()
        if clean.lower() not in sections:
            f.add("boundaries", "docs/RULES.md",
                  f"no '## {clean}' section, but ARCHITECTURE.md declares it a "
                  "boundary. Add the section, or drop the boundary.")


def check_placeholders(root: Path, limits: dict, f: Failures) -> None:
    exempt = tuple(limits["placeholder_exempt"])
    for rel in limits["placeholder_targets"]:
        if rel.startswith(exempt):
            continue
        p = root / rel
        if not p.is_file():
            continue
        for line_no, line in enumerate(read(p).split("\n"), start=1):
            for hit in PLACEHOLDER.findall(line):
                # `<e.g. ...>` is illustration inside a skeleton row; the
                # surrounding `<command>` / `<unit>` cells are not, and those
                # are exactly what an agent misreads as a real rule.
                if hit.lower().startswith("<e.g."):
                    continue
                f.add("placeholders", f"{rel}:{line_no}",
                      f"unfilled placeholder {hit} — an agent reads it as a real rule")


