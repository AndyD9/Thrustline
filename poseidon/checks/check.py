#!/usr/bin/env python3
"""Automated checks for the method kit.

Fail closed: an unreadable entry, a missing file, or an unknown argument makes a
check FAIL, never pass. Every check carries negative mutations, exercised by
`--self-test` — a check with no negative mutation may have stopped checking
anything while staying green, and that is invisible.

Usage:
    python3 check.py --all
    python3 check.py --caps --tracking
    python3 check.py --fix-index
    python3 check.py --record-baseline handlers=11 --raised-by F0001
    python3 check.py --self-test
    python3 check.py --all --root /path/to/repo --strict-placeholders
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

UNIT_ID = re.compile(r"\bF\d{4}\b")
MILESTONE_ID = re.compile(r"^###\s+(J\d+)\b", re.MULTILINE)
STATUS_LINE = re.compile(r"^Status:\s*(.*?)\s*$", re.MULTILINE)
ANY_ID = re.compile(r"\b(F\d{4}|KI-\d+|LC-\d{4}-\d+)\b")
REF_ID = re.compile(r"\b(KI-\d+|LC-\d{4}-\d+)\b")
PLACEHOLDER = re.compile(r"<[^<>\n]{2,80}>")
SKELETON_CELL = re.compile(r"^<[^>]*>$")
UNESCAPED_PIPE = re.compile(r"(?<!\\)\|")
GENERATED_BANNER = "<!-- generated by poseidon/checks/check.py — do not edit -->"


class Failures(list):
    def add(self, check: str, path, message: str) -> None:
        self.append(f"[{check}] {path}: {message}")


