def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _sub(path: Path, old: str, new: str, count: int = 1) -> None:
    text = path.read_text(encoding="utf-8")
    if old not in text:
        raise AssertionError(f"self-test fixture drift: {old!r} not in {path}")
    path.write_text(text.replace(old, new, count), encoding="utf-8")


def _append(path: Path, extra: str) -> None:
    with path.open("a", encoding="utf-8") as fh:
        fh.write(extra)


def _build_fixture(root: Path) -> None:
    for rel, content in FIXTURE.items():
        _write(root / rel, content)
    check_index(root, load_limits(root), Failures(), fix=True)


def run_self_test() -> int:
    import shutil
    problems = []
    with tempfile.TemporaryDirectory() as tmp:
        base = Path(tmp) / "base"
        base.mkdir()
        _build_fixture(base)
        limits = load_limits(base)

        f = Failures()
        for fn in CHECKS.values():
            fn(base, limits, f)
        if f:
            problems.append("clean fixture must pass, but reported:\n      "
                            + "\n      ".join(f))

        for i, (label, mutate) in enumerate(MUTATIONS):
            work = Path(tmp) / f"m{i}"
            shutil.copytree(base, work)
            mutate(work)
            f = Failures()
            for fn in CHECKS.values():
                fn(work, limits, f)
            if not f:
                problems.append(f"mutation NOT caught: {label}")
                continue
            # A mutation caught only by an unrelated check proves nothing about
            # the check it was written for.
            expected = label.split(":", 1)[0]
            if not any(line.startswith(f"[{expected}]") for line in f):
                problems.append(
                    f"mutation caught by the WRONG check: {label}\n"
                    f"      expected [{expected}], got: {f[0]}")

    if problems:
        print("SELF-TEST FAILED", file=sys.stderr)
        for p in problems:
            print("  " + p, file=sys.stderr)
        return 1
    print(f"self-test ok — clean fixture passes, "
          f"{len(MUTATIONS)} mutations each caught by their own check")
    return 0


