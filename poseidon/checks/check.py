def record_baseline(root: Path, limits: dict, spec: str, raised_by: str) -> int:
    if "=" not in spec or not UNIT_ID.fullmatch(raised_by or ""):
        print("FAIL --record-baseline needs NAME=COUNT and --raised-by FNNNN",
              file=sys.stderr)
        return 2
    name, _, count = spec.partition("=")
    if not count.isdigit():
        print(f"FAIL COUNT must be a non-negative integer, got {count!r}", file=sys.stderr)
        return 2
    p = root / limits["baselines_file"]
    data = json.loads(read(p)) if p.is_file() else {}
    prev = data.get(name, {}).get("discovered")
    if isinstance(prev, int) and int(count) < prev:
        print(f"FAIL {name}: {count} < existing baseline {prev}. A baseline never "
              "drops — something stopped running.", file=sys.stderr)
        return 1
    data[name] = {"discovered": int(count), "raised_by": raised_by}
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"baseline {name} = {count} (raised by {raised_by})")
    return 0


def adopt(root: Path, limits: dict) -> int:
    """Freeze the marker debt an existing repository already carries."""
    unregistered, bad, _ = scan_markers(root, limits)
    counts = {rel: len(lines) for rel, lines in sorted(unregistered.items())}
    p = root / limits["adoption_file"]
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(
        {"_why": "Marker debt present when the kit was adopted. This ratchet only "
                 "tightens: re-run --adopt after a cleanup unit to lower it. Never "
                 "raise a count by hand — that is how the check stops checking.",
         "markers": counts}, indent=2) + "\n", encoding="utf-8")
    total = sum(counts.values())
    print(f"adopted: {total} existing marker(s) across {len(counts)} file(s) frozen in "
          f"{limits['adoption_file']}")
    if bad:
        print(f"  note: {len(bad)} marker(s) cite a KI-/LC- id that does not exist. "
              "Those are never grandfathered — fix or remove them.")
    for rel, n in list(counts.items())[:5]:
        print(f"    {n:4}  {rel}")
    if len(counts) > 5:
        print(f"    …and {len(counts) - 5} more file(s)")
    return 0


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=".", help="repository root")
    ap.add_argument("--all", action="store_true")
    for name in CHECKS:
        ap.add_argument(f"--{name}", action="store_true")
    ap.add_argument("--strict-placeholders", action="store_true",
                    help="fail on unfilled <...> placeholders (run after install)")
    ap.add_argument("--fix-index", action="store_true",
                    help="regenerate docs/features/README.md")
    ap.add_argument("--adopt", action="store_true",
                    help="freeze the marker debt an existing repo already carries")
    ap.add_argument("--record-baseline", metavar="NAME=COUNT")
    ap.add_argument("--raised-by", metavar="FNNNN", default="")
    ap.add_argument("--self-test", action="store_true",
                    help="mutate a fixture tree and assert every mutation is caught")
    try:
        args = ap.parse_args(argv)
    except SystemExit:
        return 2  # unknown argument: fail closed

    if args.self_test:
        return run_self_test()

    root = Path(args.root).resolve()
    if not root.is_dir():
        print(f"FAIL [config] root {root} is not a directory", file=sys.stderr)
        return 2
    limits = load_limits(root)

    if args.adopt:
        return adopt(root, limits)
    if args.record_baseline:
        return record_baseline(root, limits, args.record_baseline, args.raised_by)
    if args.fix_index:
        check_index(root, limits, Failures(), fix=True)
        print("regenerated docs/features/README.md")
        return 0

    selected = [n for n in CHECKS if getattr(args, n.replace("-", "_"))]
    if args.all or not selected:
        selected = list(CHECKS)

    f = Failures()
    for name in selected:
        CHECKS[name](root, limits, f)
    if args.strict_placeholders:
        check_placeholders(root, limits, f)

    if f:
        print(f"FAILED — {len(f)} finding(s)", file=sys.stderr)
        for line in f:
            print("  " + line, file=sys.stderr)
        return 1
    print(f"ok — {len(selected)} check group(s) passed on {root}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
